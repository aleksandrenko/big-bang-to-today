"""Reconstruct coastlines (Merdith et al. 2021 plate model, 0-1000 Ma) with pygplates and write
../coasts/<Ma>.json (simplified [lon,lat] rings) plus ../coasts/index.json.
Also reconstructs the present-day locations of events (events.js `at`) to their position at that time
and writes ../paleo-points.js.   Run:  . .venv/bin/activate && python build_globe.py"""
import json, math, os, re, sys
import pygplates

M = "models/merdith2021"
ROT = pygplates.RotationModel(f"{M}/Rotations/1000_0_rotfile_Merdith_etal.rot")
COAST = pygplates.FeatureCollection(f"{M}/Coastlines/shapes_coastlines_Merdith_et_al_v2.gpmlz")
STATIC = pygplates.FeatureCollection(f"{M}/StaticPolygons/shapes_static_polygons_Merdith_etal.gpml")
OUT = "../coasts"
os.makedirs(OUT, exist_ok=True)

TIMES = list(range(0, 100, 10)) + list(range(100, 540, 20)) + list(range(540, 1001, 40))


def dp(pts, tol):
    """Douglas-Peucker on a list of (lon, lat)."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        L = dx * dx + dy * dy
        best, bi = -1, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            if L == 0:
                d = math.hypot(px - ax, py - ay)
            else:
                t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / L))
                d = math.hypot(px - ax - t * dx, py - ay - t * dy)
            if d > best:
                best, bi = d, i
        if best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def ring_area_deg(r):
    a = 0
    for i in range(len(r)):
        x1, y1 = r[i]; x2, y2 = r[(i + 1) % len(r)]
        a += x1 * y2 - x2 * y1
    return abs(a) / 2


index = []
wrapper = pygplates.DateLineWrapper()
for t in TIMES:
    rec = []
    pygplates.reconstruct(COAST, ROT, rec, t)
    rings = []
    for r in rec:
        g = r.get_reconstructed_geometry()
        if not isinstance(g, pygplates.PolygonOnSphere):
            continue
        for poly in wrapper.wrap(g):
            pts = [(p.get_longitude(), p.get_latitude()) for p in poly.get_exterior_points()]
            if ring_area_deg(pts) < 0.6:  # drop specks
                continue
            s = dp(pts, 0.25)
            if len(s) < 4:
                continue
            rings.append([v for p in s for v in (round(p[0], 1), round(p[1], 1))])
    with open(f"{OUT}/{t}.json", "w") as f:
        json.dump(rings, f, separators=(",", ":"))
    size = os.path.getsize(f"{OUT}/{t}.json")
    index.append(t)
    print(t, "Ma:", len(rings), "rings", size // 1024, "KB")
with open(f"{OUT}/index.json", "w") as f:
    json.dump(index, f)

# ---- event locations at their own time ----
import subprocess
points = {}
if os.path.exists("../events.js"):
    # let node read the data file, so any JS formatting works
    js = open("../events.js", encoding="utf-8").read() + "\nconsole.log(JSON.stringify(EVENTS.filter(e => e.at).map(e => [e.id, e.ago, e.at])))"
    rows = json.loads(subprocess.run(["node", "-e", js], capture_output=True, text=True, check=True).stdout)
    for eid, years, (lon, lat) in rows:
        ma = years / 1e6
        if ma < 0.5:
            points[eid] = [lon, lat]
            continue
        feat = pygplates.Feature()
        feat.set_geometry(pygplates.PointOnSphere(lat, lon))
        assigned = pygplates.partition_into_plates(STATIC, ROT, [feat], properties_to_copy=[pygplates.PartitionProperty.reconstruction_plate_id])
        rec = []
        pygplates.reconstruct(assigned, ROT, rec, min(ma, 1000))
        if rec:
            p = rec[0].get_reconstructed_geometry().to_lat_lon()
            points[eid] = [round(p[1], 2), round(p[0], 2)]
if points:
    with open("../paleo-points.js", "w") as f:
        f.write("/* generated by data-src/build_globe.py: where each place was at the time of its event (Merdith et al. 2021) */\n")
        f.write("const PALEO_AT = " + json.dumps(points, ensure_ascii=False) + ";\n")
    print("points:", len(points))
